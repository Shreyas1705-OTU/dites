-- Dites core schema (v1.0 data model).
-- RLS policies and grants live in the next migration; every table here has
-- RLS enabled immediately so nothing is ever readable without a policy.

-- ---------------------------------------------------------------------------
-- Private schema: internal tables and helper functions. It is not in the
-- Data API's exposed schemas, so PostgREST cannot reach it directly.
-- ---------------------------------------------------------------------------
create schema if not exists private;
revoke all on schema private from public, anon;
-- authenticated needs USAGE so RLS policies can call private helpers;
-- it gets no table privileges in this schema.
grant usage on schema private to authenticated;

-- ---------------------------------------------------------------------------
-- profiles
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  display_name text,
  avatar_path text,
  is_guest boolean not null default false,
  created_at timestamptz not null default now(),
  constraint profiles_username_format check (username ~ '^[a-z0-9_]{3,20}$'),
  constraint profiles_username_not_reserved check (
    username <> all (array[
      'admin', 'administrator', 'dites', 'root', 'system', 'support',
      'moderator', 'mod', 'staff', 'official', 'security', 'help',
      'null', 'undefined', 'anonymous', 'guest', 'bot', 'api'
    ])
  ),
  constraint profiles_display_name_length check (char_length(display_name) between 1 and 50)
);
alter table public.profiles enable row level security;

-- ---------------------------------------------------------------------------
-- rooms
-- ---------------------------------------------------------------------------
create table public.rooms (
  id uuid primary key default gen_random_uuid(),
  type text not null,
  name text,
  description text,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint rooms_type_valid check (type in ('public', 'private', 'dm')),
  -- DMs are unnamed; public and private rooms need a name.
  constraint rooms_name_by_type check (
    (type = 'dm' and name is null and description is null)
    or (type <> 'dm' and name is not null and char_length(btrim(name)) between 1 and 50)
  ),
  constraint rooms_description_length check (char_length(description) <= 200)
);
alter table public.rooms enable row level security;
create index rooms_created_by_created_at_idx on public.rooms (created_by, created_at);

-- ---------------------------------------------------------------------------
-- room_members
-- ---------------------------------------------------------------------------
create table public.room_members (
  room_id uuid not null references public.rooms (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  role text not null default 'member',
  joined_at timestamptz not null default now(),
  last_read_at timestamptz not null default now(),
  primary key (room_id, user_id),
  constraint room_members_role_valid check (role in ('owner', 'member'))
);
alter table public.room_members enable row level security;
-- The primary key covers lookups by room; this covers "my rooms".
create index room_members_user_id_idx on public.room_members (user_id);

-- ---------------------------------------------------------------------------
-- messages
-- id is generated by the client so retries are idempotent (same id = same row).
-- ---------------------------------------------------------------------------
create table public.messages (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms (id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  body text,
  image_path text,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  constraint messages_body_length check (char_length(body) between 1 and 2000),
  -- A live message has content; a soft-deleted one has its content cleared.
  constraint messages_has_content check (
    deleted_at is not null or body is not null or image_path is not null
  )
);
alter table public.messages enable row level security;
-- Cursor pagination: newest first within a room.
create index messages_room_created_idx on public.messages (room_id, created_at desc, id desc);
-- Rate limiting: a user's recent messages.
create index messages_user_created_idx on public.messages (user_id, created_at desc);

-- ---------------------------------------------------------------------------
-- blocks
-- ---------------------------------------------------------------------------
create table public.blocks (
  blocker_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  blocked_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint blocks_not_self check (blocker_id <> blocked_id)
);
alter table public.blocks enable row level security;
create index blocks_blocked_id_idx on public.blocks (blocked_id);

-- ---------------------------------------------------------------------------
-- reports
-- ---------------------------------------------------------------------------
create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  message_id uuid not null references public.messages (id) on delete cascade,
  reason text not null,
  created_at timestamptz not null default now(),
  resolved boolean not null default false,
  constraint reports_reason_length check (char_length(btrim(reason)) between 1 and 500)
);
alter table public.reports enable row level security;
create index reports_reporter_created_idx on public.reports (reporter_id, created_at desc);
create index reports_message_id_idx on public.reports (message_id);

-- ---------------------------------------------------------------------------
-- DM pair registry: enforces one DM per pair of users in the database.
-- user_a is always the smaller uuid, so (a, b) and (b, a) collide.
-- ---------------------------------------------------------------------------
create table private.dm_pairs (
  user_a uuid not null references public.profiles (id) on delete cascade,
  user_b uuid not null references public.profiles (id) on delete cascade,
  room_id uuid not null unique references public.rooms (id) on delete cascade,
  primary key (user_a, user_b),
  constraint dm_pairs_ordered check (user_a < user_b)
);
alter table private.dm_pairs enable row level security;
create index dm_pairs_user_b_idx on private.dm_pairs (user_b);

-- ---------------------------------------------------------------------------
-- bans and admins (private: never exposed through the API)
-- ---------------------------------------------------------------------------
create table private.bans (
  user_id uuid primary key references auth.users (id) on delete cascade,
  reason text,
  created_at timestamptz not null default now()
);
alter table private.bans enable row level security;

create table private.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table private.admins enable row level security;
